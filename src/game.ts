export function abilityAvailable(s: State, now = Date.now()) {
  if (now < s.worldReady) return false;
  if ([0, 1, 2, 4, 5, 8, 10].includes(s.world)) return s.worldMeter >= 10;
  if (s.world === 6) return s.worldStacks < 10 && s.counts.some((n) => n > 0);
  if (s.world === 7) return s.worldStacks < 10 && s.energy >= 1000;
  return true;
}
export function worldAbility(s: State, now = Date.now()) {
  if (!abilityAvailable(s, now)) return false;
  const rate = production(s),
    meter = s.worldMeter / 100,
    types = s.counts.filter((n) => n > 0).length;
  let seconds = 0;
  switch (s.world) {
    case 0:
      seconds = 60 * meter;
      break;
    case 1:
      seconds = 90 * meter;
      break;
    case 2:
      seconds = 40 * meter;
      s.charge = Math.min(100, s.charge + s.worldMeter);
      break;
    case 3:
      seconds = 5 * types;
      break;
    case 4:
      seconds = 100 * meter;
      break;
    case 5:
      s.charge = Math.min(100, s.charge + s.worldMeter);
      break;
    case 6: {
      const i = s.counts.findIndex((n) => n > 0);
      s.counts[i]--;
      s.worldStacks++;
      break;
    }
    case 7:
      s.energy -= Math.max(100, s.energy * 0.1);
      s.worldStacks++;
      break;
    case 8:
      seconds = 180 * meter;
      break;
    case 9:
      seconds = 30;
      s.charge = Math.min(100, s.charge + 30);
      break;
    case 10:
      seconds = 120 * meter;
      break;
    case 11:
      seconds = 10 * types;
      s.charge = 100;
      break;
  }
  gain(s, rate * seconds);
  s.worldMeter = 0;
  s.worldReady = now + 90000;
  return true;
}
// A single ordered pass: one selected batch per structure type, all affordable research.
// Relics deliberately retain individual purchases; the Legacy bulk action only claims rewards.
export function buyAll(s: State, kind: string, qty = 1) {
  let bought = 0;
  if (kind === "structures")
    units.forEach((_, i) => {
      if (buy(s, i, qty)) bought += qty;
    });
  if (kind === "research")
    research.forEach((_, i) => {
      if (learn(s, i)) bought++;
    });
  if (kind === "legacy") {
    challenges.forEach((_, i) => {
      if (claimChallenge(s, i)) bought++;
    });
    sectors.forEach((_, i) => {
      if (claimSector(s, i)) bought++;
    });
  }
  return bought;
}
export function advance(s: State, from: number, to: number) {
  const end = Math.max(from, to),
    start = Math.max(from, end - 8 * 3600000),
    boosted = Math.max(0, Math.min(end, s.boostUntil) - start);
  const elapsed = (end - start) / 1000;
  const growthRate =
    s.world === 4
      ? 1
      : s.world === 5
        ? 2
        : s.world === 8
          ? 0.5
          : s.world === 10
            ? 1
            : 0;
  let earned =
    (production(s) * (end - start + (boostMultiplier(s) - 1) * boosted)) / 1000;
  if (s.world === 10) {
    const base = production(s) / worldFactor(s),
      initial = s.worldMeter;
    const integral = (seconds: number) => {
      const rising = Math.min(seconds, 100 - initial);
      return (
        seconds * (1 + initial / 100) +
        (rising * rising) / 200 +
        ((seconds - rising) * (100 - initial)) / 100
      );
    };
    earned =
      base *
      (integral(elapsed) + (boostMultiplier(s) - 1) * integral(boosted / 1000));
  }
  s.worldMeter = Math.min(100, s.worldMeter + elapsed * growthRate);
  gain(s, earned);
  if (end >= s.nextComet + 15000) s.nextComet = end + 45000;
  return earned;
}
export const automationUnlocked = (s: State) => s.ascensions >= 1;
// Foreground automation has a fixed per-tick spending budget, never offline catch-up.
export function automate(s: State, now = Date.now()) {
  if (!s.autoEnabled || !automationUnlocked(s) || now < s.nextAuto) return 0;
  s.nextAuto = now + 1000;
  let budget = (s.energy * s.autoBudget) / 100,
    bought = 0;
  for (let step = 0; step < 10; step++) {
    const candidates = units
      .map((u, i) => ({
        i,
        cost: price(s, i),
        score: s.autoPolicy === "cheapest" ? price(s, i) : price(s, i) / u.rate,
      }))
      .filter((x) => canBuild(s, x.i) && x.cost <= budget)
      .sort((a, b) => a.score - b.score);
    if (!candidates.length) break;
    const item = candidates[0];
    if (!buy(s, item.i, 1)) break;
    budget -= item.cost;
    bought++;
  }
  return bought;
}
export function passiveActions(s: State, now = Date.now()) {
  if (rank(s, 11)) catchComet(s, now);
  return automate(s, now);
}
export const ascensionReward = (s: State) =>
  Math.floor(Math.sqrt(s.earned / 100000));
export const echoReward = (s: State) =>
  s.earned < 1e6
    ? 0
    : Math.floor(
        (Math.floor(Math.log10(s.earned / 1e6)) +
          (sectorIndex(s) === 3 ? 5 : 0) +
          1 +
          Math.max(0, s.world - 2)) *
          (rank(s, 7) ? 1.5 : 1) *
          (rank(s, 13) ? 2 : 1),
      );
function resetRun(s: State) {
  recordMilestones(s);
  return {
    ...fresh(),
    shards: s.shards,
    echoes: s.echoes,
    relics: [...s.relics],
    claimed: [...s.claimed],
    completedTrials: [...s.completedTrials],
    artifacts: [...s.artifacts],
    bestWorld: s.bestWorld,
    bestResearch: s.bestResearch,
    bestStructures: s.bestStructures,
    totalClicks: s.totalClicks,
    comets: s.comets,
    lifetime: s.lifetime,
    ascensions: s.ascensions,
    theme: s.theme,
    sectorClaims: [...s.sectorClaims],
    sound: s.sound,
    autoEnabled: s.autoEnabled,
    autoPolicy: s.autoPolicy,
    autoBudget: s.autoBudget,
  };
}
export function ascend(s: State): State {
  if (s.trial >= 0 || ascensionReward(s) < 1) return s;
  const next = resetRun(s);
  next.shards += ascensionReward(s);
  next.echoes += echoReward(s);
  next.ascensions++;
  next.counts[0] = next.relics[0] * 5;
  if (next.relics[9]) next.counts[5] = 10;
  if (next.relics[6]) next.upgrades = [0, 1, 2];
  if (next.relics[12]) next.upgrades = Array.from({ length: 12 }, (_, i) => i);
  recordMilestones(next);
  return next;
}
export function startTrial(s: State, i: number): State {
  if (!trials[i] || s.ascensions < 1 || s.trial >= 0) return s;
  const next = resetRun(s);
  next.trial = i;
  next.autoEnabled = false;
  if (i === 0) next.counts[0] = 1;
  return next;
}
export function finishTrial(s: State, abandon = false): State {
  if (s.trial < 0 || (!abandon && s.earned < trials[s.trial].target)) return s;
  const next = resetRun(s);
  if (!abandon && !next.completedTrials.includes(s.trial)) {
    next.completedTrials.push(s.trial);
    next.echoes += trials[s.trial].reward;
  }
  next.counts[0] = next.relics[0] * 5;
  if (next.relics[9]) next.counts[5] = 10;
  if (next.relics[6]) next.upgrades = [0, 1, 2];
  if (next.relics[12]) next.upgrades = Array.from({ length: 12 }, (_, i) => i);
  return next;
}
// Accept the original six-structure save without discarding the player's progress.
export function parseSave(value: unknown): State | null {
  if (!value || typeof value !== "object") return null;
  const s = value as Record<string, unknown>;
  const numbers = [
    "energy",
    "earned",
    "lifetime",
    "clicks",
    "shards",
    "ascensions",
    "savedAt",
  ];
  if (
    numbers.some(
      (k) =>
        typeof s[k] !== "number" || !Number.isFinite(s[k]) || Number(s[k]) < 0,
    )
  )
    return null;
  const integer = (n: unknown) => Number.isSafeInteger(n) && Number(n) >= 0;
  const ids = (v: unknown, max: number) =>
    Array.isArray(v) &&
    v.every((n) => integer(n) && Number(n) < max) &&
    new Set(v).size === v.length;
  if (
    !Array.isArray(s.counts) ||
    ![6, 12, units.length].includes(s.counts.length) ||
    !s.counts.every(integer) ||
    !ids(s.upgrades, research.length) ||
    !integer(s.world) ||
    Number(s.world) >= worlds.length
  )
    return null;
  for (const k of [
    "echoes",
    "bestWorld",
    "bestResearch",
    "bestStructures",
    "totalClicks",
    "comets",
    "charge",
    "boostUntil",
    "nextComet",
  ])
    if (s[k] !== undefined && !integer(s[k])) return null;
  if (
    s.relics !== undefined &&
    (!Array.isArray(s.relics) ||
      ![8, relics.length].includes(s.relics.length) ||
      !s.relics.every((n, i) => integer(n) && n <= relics[i].max))
  )
    return null;
  if (s.claimed !== undefined && !ids(s.claimed, challenges.length))
    return null;
  if (
    s.role !== undefined &&
    (!Number.isInteger(s.role) ||
      Number(s.role) < -1 ||
      Number(s.role) >= roles.length)
  )
    return null;
  if (
    s.trial !== undefined &&
    (!Number.isInteger(s.trial) ||
      Number(s.trial) < -1 ||
      Number(s.trial) >= trials.length)
  )
    return null;
  if (s.completedTrials !== undefined && !ids(s.completedTrials, trials.length))
    return null;
  if (
    s.artifacts !== undefined &&
    (!ids(s.artifacts, artifacts.length) ||
      (s.artifacts as number[]).length > 3)
  )
    return null;
  if (
    s.autoPolicy !== undefined &&
    !["efficient", "cheapest"].includes(String(s.autoPolicy))
  )
    return null;
  if (
    s.autoBudget !== undefined &&
    ![10, 25, 50].includes(Number(s.autoBudget))
  )
    return null;
  for (const k of ["worldReady", "nextAuto"])
    if (s[k] !== undefined && !integer(s[k])) return null;
  if (s.theme !== undefined && !themes.some((t) => t.id === s.theme))
    return null;
  if (
    s.worldMeter !== undefined &&
    (typeof s.worldMeter !== "number" ||
      !Number.isFinite(s.worldMeter) ||
      s.worldMeter < 0 ||
      s.worldMeter > 100)
  )
    return null;
  if (
    s.worldStacks !== undefined &&
    (!integer(s.worldStacks) || Number(s.worldStacks) > 10)
  )
    return null;
  if (s.sectorClaims !== undefined && !ids(s.sectorClaims, sectors.length))
    return null;
  const result = {
    ...fresh(),
    ...s,
    counts: [...s.counts, ...Array(units.length - s.counts.length).fill(0)],
    relics: Array.from({ length: relics.length }, (_, i) =>
      Array.isArray(s.relics) ? (s.relics[i] ?? 0) : 0,
    ),
    autoEnabled: s.autoEnabled === true,
    upgrades: [...(s.upgrades as number[])],
    sound: s.sound === true,
  } as State;
  if (
    result.bestWorld >= worlds.length ||
    result.bestResearch > research.length ||
    result.charge > 100
  )
    return null;
  result.totalClicks = Math.max(result.totalClicks, result.clicks);
  recordMilestones(result);
  return result;
}
export function load(): State {
  try {
    return (
      parseSave(
        JSON.parse(localStorage.getItem("aether-forge-v1") ?? "null"),
      ) ?? fresh()
    );
  } catch {
    return fresh();
  }
}
export function save(s: State) {
  s.savedAt = Date.now();
  try {
    localStorage.setItem("aether-forge-v1", JSON.stringify(s));
    return true;
  } catch {
    return false;
  }
}
export function format(n: number) {
  if (n < 1000)
    return n.toLocaleString("en-US", { maximumFractionDigits: n < 10 ? 1 : 0 });
  if (n >= 1e24) return n.toExponential(2);
  const suffix = ["K", "M", "B", "T", "Qa", "Qi", "Sx"];
  let i = -1;
  while (n >= 1000 && i < suffix.length - 1) {
    n /= 1000;
    i++;
  }
  return n.toFixed(n < 10 ? 2 : n < 100 ? 1 : 0) + suffix[i];
}
